import fs from 'fs';
import path from 'path';

const root = path.resolve(process.cwd());
const order = [
  'js/core/events.js',
  'js/core/store.js',
  'js/core/dom.js',
  'js/core/i18n.js',
  'js/core/admin.js',
  'js/utils/math.js',
  'js/utils/format.js',
  'js/i18n/strings.es.js',
  'js/i18n/strings.en.js',
  'js/data/fallback.js',
  'js/data/favorites.js',
  'js/data/userdata.js',
  'js/data/service.js',
  'js/effects/loader.js',
  'js/effects/cursor.js',
  'js/effects/glitch.js',
  'js/effects/particles.js',
  'js/effects/artgen.js',
  'js/graph/model.js',
  'js/graph/camera.js',
  'js/graph/layout.js',
  'js/graph/edges.js',
  'js/graph/nodes.js',
  'js/graph/graph.js',
  'js/ui/toast.js',
  'js/ui/theme-switch.js',
  'js/ui/search.js',
  'js/ui/sidebar.js',
  'js/ui/gallery.js',
  'js/ui/modal.js',
  'js/ui/node-picker.js',
  'js/ui/editor.js',
  'js/ui/toolbar.js',
  'js/main.js'
];

const chunks = order.map(function (file) {
  return fs.readFileSync(path.join(root, file), 'utf8')
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map(function (line) { return line.trimEnd(); })
    .join('\n');
});

const header = [
  '/* ============================================================',
  '   KARL_SKETCH - Production JS Bundle',
  '   Generated by scripts/build.js',
  '   ============================================================ */',
  ''
].join('\n');

fs.writeFileSync(path.join(root, 'js/app.min.js'), header + chunks.join('\n;\n'));
console.log('Bundle actualizado: js/app.min.js (' + order.length + ' archivos)');
